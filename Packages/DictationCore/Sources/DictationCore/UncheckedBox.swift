/// Обёртка для значений, которые компилятор считает небезопасными для передачи
/// между потоками, хотя на деле они используются в одном.
///
/// Нужна для звуковых API: `AVAudioConverter.convert` принимает замыкание,
/// помеченное как параллельное, но вызывает его синхронно на том же потоке, что
/// и сам вызов. Без обёртки компилятор запрещает передать туда буфер, а
/// отключать проверки во всём файле — значит потерять их там, где они полезны.
public final class UncheckedBox<Value>: @unchecked Sendable {
    public var value: Value

    public init(_ value: Value) {
        self.value = value
    }
}
