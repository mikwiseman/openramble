import Foundation

/// Как часто опрашивать разрешения.
///
/// Разрешения выдают и отзывают в системных настройках, приложению об этом не
/// сообщают — состояние приходится спрашивать самим.
///
/// Соблазн был замедлять опрос, когда всё выдано: приложение живёт в строке
/// меню неделями, и секундный таймер всё это время — миллионы пробуждений ради
/// ответа, который меняется однажды. От этого отказались сознательно. Отзыв
/// доступа не присылает надёжного события, а приложение с отозванным
/// Accessibility выглядит целым и молча не работает — значок в строке меню
/// обязан сказать об этом не позже двух секунд, в том числе из полного покоя.
/// Пока идёт safe beta, честность значка дороже сэкономленных пробуждений.
///
/// Отсюда и вид функции: выданные разрешения на промежуток не влияют, и
/// единственный способ выключить опрос — задать нулевой `base` снаружи.
/// Вернуть замедление можно будет тогда, когда появится надёжное уведомление
/// об отзыве, — но не раньше.
enum PermissionPollPolicy {
    /// Возвращает промежуток между опросами. Ноль — не опрашивать.
    static func interval(
        accessibilityGranted: Bool,
        microphoneGranted: Bool,
        base: TimeInterval
    ) -> TimeInterval {
        // Ноль означает «опрос выключен снаружи» — так делают тесты.
        guard base > 0 else { return 0 }

        // Оба флага намеренно не используются: см. решение в шапке типа. Они
        // остаются в сигнатуре, потому что именно они вернутся в расчёт, когда
        // у отзыва появится надёжное уведомление.
        _ = accessibilityGranted
        _ = microphoneGranted
        return min(base, 2)
    }
}
