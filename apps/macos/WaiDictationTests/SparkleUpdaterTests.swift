import XCTest

/// Обновления — второе и последнее место продукта, которое ходит в сеть.
@MainActor
final class SparkleUpdaterTests: XCTestCase {
    /// В тестовом бандле открытого ключа подписи нет — ровно тот случай, ради
    /// которого проверка и написана.
    ///
    /// Собственная проверка Sparkle здесь дырявая: при HTTPS-адресе фида и
    /// подписанном приложении она пропускает отсутствие ключа и запускается,
    /// оставив обновления на одной лишь подписи кода. Молчать об этом нельзя:
    /// человек будет считать, что обновления приходят.
    func testБезКлючаПодписиОбновленияОтключаютсяИГоворятОбЭтом() throws {
        let updater = SparkleUpdater()

        let failure = try XCTUnwrap(
            updater.startupFailure,
            "без ключа подписи обновления обязаны отказать вслух, а не молча ослабнуть"
        )
        XCTAssertTrue(failure.contains("SUPublicEDKey"), "«\(failure)» не называет, чего не хватает")
        XCTAssertTrue(failure.contains("Обновления отключены"))
    }
}
